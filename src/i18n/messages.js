const getByPath = (obj, path) => {
  return path.split('.').reduce((acc, key) => (acc && acc[key] !== undefined ? acc[key] : null), obj);
};

export const formatMessage = (lang, key) => {
  const message = getByPath(messages[lang], key);
  return message || key;
};

